def accrue(shipment: dict) -> dict:
    r = ops().post("/finance/accruals/rebuild", json={"shipment_id": shipment["id"]})
    assert r.status_code == 200, r.text
    rows = [x for x in r.json()["items"] if x["status"] == "open"]
    assert len(rows) == 1, r.json()
    return rows[0]


# ------------------------------------------------------------------------------------------- autopilot
@contextlib.contextmanager
def autopilot(enabled: bool):
    before = bool((db.settings.find_one({"key": "app"}) or {}).get("autopilot_enabled"))
    _set_autopilot(enabled)
    try:
        yield
    finally:
        _set_autopilot(before)


def _set_autopilot(enabled: bool):
    r = ops().post("/settings/autonomy/autopilot_enabled", json={"enabled": enabled, "confirmation": "enable" if enabled else ""})
    assert r.status_code == 200, r.text


