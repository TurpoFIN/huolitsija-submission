def send_mail(to: str, subject: str, attachments: list[tuple[str, bytes, str]], sender: str) -> str:
    msg = EmailMessage()
    msg["From"] = sender
    msg["To"] = to
    msg["Subject"] = subject
    msg_id = f"<{uuid.uuid4().hex}@carrier.test>"
    msg["Message-ID"] = msg_id
    msg.set_content("Liitteenä lasku. Invoice attached.")
    for name, data, ctype in attachments:
        maintype, subtype = ctype.split("/")
        msg.add_attachment(data, maintype=maintype, subtype=subtype, filename=name)
    with smtplib.SMTP(*SMTP, timeout=20) as s:
        s.send_message(msg)
    return msg_id


def imap_messages(address: str, subject_contains: str | None = None) -> list:
    m = imaplib.IMAP4(*IMAP, timeout=20)
    try:
        m.login(address, IMAP_PASSWORD)
        m.select("INBOX")
        typ, data = m.search(None, "ALL")
        out = []
        for num in (data[0] or b"").split():
            typ, raw = m.fetch(num, "(BODY.PEEK[])")
            msg = BytesParser(policy=policy.default).parsebytes(raw[0][1])
            if subject_contains is None or subject_contains in str(msg.get("Subject")):
                out.append(msg)
        return out
    finally:
        m.logout()


def imap_unseen_ids(address: str) -> set[str]:
    m = imaplib.IMAP4(*IMAP, timeout=20)
    try:
        m.login(address, IMAP_PASSWORD)
        m.select("INBOX")
        typ, data = m.search(None, "UNSEEN")
        out = set()
        for num in (data[0] or b"").split():
            typ, raw = m.fetch(num, "(BODY.PEEK[HEADER.FIELDS (MESSAGE-ID)])")
            out.add(raw[0][1].decode().split(":", 1)[-1].strip())
        return out
    finally:
        m.logout()
