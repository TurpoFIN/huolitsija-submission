def expected_cost_cents(lines: list[dict]) -> int:
    from decimal import Decimal
    total = Decimal(0)
    for ln in lines:
        if ln.get("is_pass_through") or (ln.get("payer") or "").lower() == "third_party":
            continue
        total += Decimal(ln["unit_cost_cents"]) * Decimal(str(ln["qty"]))
    return int(total)


