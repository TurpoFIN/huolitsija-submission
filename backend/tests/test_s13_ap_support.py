def fi_iban() -> str:
    """A fresh Finnish IBAN with a correct ISO 13616 check (independent of the backend's validator)."""
    bban = "".join(random.choice("0123456789") for _ in range(14))
    check = 98 - int(bban + "1518" + "00") % 97  # F=15 I=18
    return f"FI{check:02d}{bban}"


def container_no(owner: str = "TSTU") -> str:
    digits = "".join(random.choice("0123456789") for _ in range(6))
    vals, v = {}, 10
    for ch in "ABCDEFGHIJKLMNOPQRSTUVWXYZ":
        if v in (11, 22, 33):
            v += 1
        vals[ch] = v
        v += 1
    s = owner + digits
    total = sum((vals[c] if c.isalpha() else int(c)) * 2 ** i for i, c in enumerate(s))
    return s + str(total % 11 % 10)


