const D = { en, fi };

/** t() for the partner screens: own strings first (fi, then en), then the shared dictionaries. */
export function usePT() {
  const { t, locale } = useT();
  const pt = useCallback(
    (key, vars) => {
      const s = (D[locale] && D[locale][key]) ?? D.en[key];
      if (s === undefined) return t(key, vars);
      return vars ? s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] === undefined || vars[k] === null ? "" : String(vars[k]))) : s;
    },
    [t, locale],
  );
  return { t, pt, locale };
}

export default D;
